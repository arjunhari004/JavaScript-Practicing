//Increment Decrement operator

let a=10;
console.log("Before Decrement",a);
a++;//a=a+1
console.log("After Increment",a);


let b=5;
console.log("Before Decrement",b);
b--;//b+b-1
console.log("After Decrement",b);


//POST DECREMENT

let c=5;
console.log(c++);
console.log(c);


//PRE DECREMENT


let d=4;
console.log(++d);
console.log(d);


let e=5;
let res=e++ + e++;

console.log(res);//11
console.log(e);//7


let f=10;
let res2=f++ + f++;
console.log(res2);
